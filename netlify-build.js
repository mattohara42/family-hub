/**
 * netlify-build.js: runs during Netlify deploy (before files are published)
 *
 * 1. Stamps a unique CACHE_VERSION into sw.js so every deploy invalidates the
 *    old service worker cache and users always get fresh app shell files.
 * 2. If the GOOGLE_CLIENT_ID and FIREBASE_CONFIG env vars are set, rewrites
 *    config.js from them. That's how a fork runs its own Google/Firebase
 *    projects without editing a tracked file. With neither set, the committed
 *    config.js ships as is. Setting only one fails the build, since half a
 *    config would sign in against one project and read data from another.
 * 3. Points the absolute link-preview URLs in family-hub.html (og:url,
 *    og:image, twitter:image) at this site, using Netlify's own URL env var.
 *    A no-op on the original site; a fork's previews stop naming it.
 */
const fs = require('fs');
const vm = require('vm');

/**
 * FIREBASE_CONFIG may be strict JSON or the JS snippet Firebase Console shows
 * (unquoted keys, optionally wrapped in `const firebaseConfig = {...};`).
 * Evaluated in an empty vm context: it's the site owner's own env var.
 */
function parseFirebaseConfig(raw) {
  const literal = raw.trim()
    .replace(/^(?:const|let|var)\s+\w+\s*=\s*/, '')
    .replace(/;\s*$/, '');
  let cfg;
  try {
    cfg = vm.runInNewContext(`(${literal})`, Object.create(null), { timeout: 1000 });
  } catch (e) {
    throw new Error(`FIREBASE_CONFIG is not a valid object: ${e.message}`);
  }
  if (!cfg || typeof cfg !== 'object' || !cfg.apiKey || !cfg.projectId) {
    throw new Error('FIREBASE_CONFIG must be an object with at least apiKey and projectId');
  }
  return cfg;
}

/** Returns config.js source from env, or null to keep the committed file. */
function buildConfigJs(env) {
  const clientId = (env.GOOGLE_CLIENT_ID || '').trim();
  const firebaseRaw = (env.FIREBASE_CONFIG || '').trim();
  if (!clientId && !firebaseRaw) return null;
  if (!clientId || !firebaseRaw) {
    throw new Error('Set both GOOGLE_CLIENT_ID and FIREBASE_CONFIG, or neither');
  }
  const config = { firebase: parseFirebaseConfig(firebaseRaw), googleClientId: clientId };
  return '// Generated by netlify-build.js from the GOOGLE_CLIENT_ID and FIREBASE_CONFIG\n'
       + '// env vars. Edit those in Netlify, not this file.\n'
       + `window.FH_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
}

// The origin committed in family-hub.html's Open Graph tags.
const COMMITTED_ORIGIN = 'https://familial.netlify.app';

/** Returns html with the committed origin replaced by siteUrl's origin. */
function stampSiteOrigin(html, siteUrl) {
  if (!siteUrl) return html;
  const origin = new URL(siteUrl).origin;
  return html.split(COMMITTED_ORIGIN).join(origin);
}

if (require.main === module) {
  const version = `fh-${Date.now()}`;

  // Patch sw.js
  const sw = fs.readFileSync('sw.js', 'utf8');
  const patched = sw.replace(/const CACHE_VERSION = 'fh-[^']*'/, `const CACHE_VERSION = '${version}'`);
  fs.writeFileSync('sw.js', patched);

  console.log(`[netlify-build] SW cache version set to: ${version}`);

  const configJs = buildConfigJs(process.env);
  if (configJs) {
    fs.writeFileSync('config.js', configJs);
    console.log('[netlify-build] config.js written from GOOGLE_CLIENT_ID + FIREBASE_CONFIG');
  } else {
    console.log('[netlify-build] No GOOGLE_CLIENT_ID/FIREBASE_CONFIG env vars; using committed config.js');
  }

  const html = fs.readFileSync('family-hub.html', 'utf8');
  const stamped = stampSiteOrigin(html, process.env.URL);
  if (stamped !== html) {
    fs.writeFileSync('family-hub.html', stamped);
    console.log(`[netlify-build] Link-preview URLs pointed at ${new URL(process.env.URL).origin}`);
  }
}

module.exports = { buildConfigJs, parseFirebaseConfig, stampSiteOrigin };
